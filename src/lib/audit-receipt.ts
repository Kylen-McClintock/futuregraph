import crypto from "crypto";
import { AuditReceipt } from "@/types/futuregraph";

const DEFAULT_SIGNING_SECRET =
  process.env.FUTUREGRAPH_RECEIPT_SIGNING_SECRET ||
  "futuregraph-mvp-default-server-hmac-secret-2026";

/**
 * Recursively sorts object keys to produce deterministic canonical JSON serialization.
 */
export function canonicalizePayload(value: unknown): string {
  if (value === null || typeof value !== "object") {
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) {
    return "[" + value.map((item) => canonicalizePayload(item)).join(",") + "]";
  }
  const record = value as Record<string, unknown>;
  const sortedKeys = Object.keys(record).sort();
  const pairs = sortedKeys
    .filter((k) => record[k] !== undefined)
    .map((k) => `${JSON.stringify(k)}:${canonicalizePayload(record[k])}`);
  return "{" + pairs.join(",") + "}";
}

export function sha256Hex(input: string): string {
  return crypto.createHash("sha256").update(input, "utf8").digest("hex");
}

export function hmacSha256Hex(input: string, secret = DEFAULT_SIGNING_SECRET): string {
  return crypto.createHmac("sha256", secret).update(input, "utf8").digest("hex");
}

/**
 * Creates a server-timestamped, SHA-256 hash-chained tamper-evident receipt.
 */
export function createServerAuditReceipt(params: {
  eventId: string;
  entityType: AuditReceipt["entityType"];
  entityId: string;
  contributorId: string;
  contributorHandle: string;
  contributorName: string;
  agentMetadata?: AuditReceipt["agentMetadata"];
  scenarioVersion: number;
  canonicalPayload: Record<string, unknown>;
  prevReceiptHash?: string | null;
  serverTimestamp?: string;
}): AuditReceipt {
  const serverTimestamp = params.serverTimestamp || new Date().toISOString();
  const canonicalString = canonicalizePayload(params.canonicalPayload);
  const payloadSha256 = sha256Hex(canonicalString);
  const prevHash = params.prevReceiptHash || "GENESIS_FUTUREGRAPH_AI2027_V1";
  const chainInput = `${prevHash}:${payloadSha256}:${serverTimestamp}:${params.contributorId}:${params.scenarioVersion}`;
  const chainSha256 = sha256Hex(chainInput);
  const hmacSignature = hmacSha256Hex(`${params.eventId}:${chainSha256}`);

  return {
    eventId: params.eventId,
    entityType: params.entityType,
    entityId: params.entityId,
    contributorId: params.contributorId,
    contributorHandle: params.contributorHandle,
    contributorName: params.contributorName,
    agentMetadata: params.agentMetadata || null,
    scenarioVersion: params.scenarioVersion,
    canonicalPayload: params.canonicalPayload,
    payloadSha256,
    prevReceiptHash: params.prevReceiptHash || null,
    chainSha256,
    hmacSignature,
    serverTimestamp,
  };
}

/**
 * Verifies an AuditReceipt's payload SHA-256 hash and chain hash integrity.
 */
export function verifyAuditReceipt(receipt: AuditReceipt): {
  verified: boolean;
  recomputedPayloadHash: string;
  recomputedChainHash: string;
  payloadMatches: boolean;
  chainMatches: boolean;
  limitationsDisclosure: string;
} {
  const canonicalString = canonicalizePayload(receipt.canonicalPayload);
  const recomputedPayloadHash = sha256Hex(canonicalString);
  const prevHash = receipt.prevReceiptHash || "GENESIS_FUTUREGRAPH_AI2027_V1";
  const chainInput = `${prevHash}:${recomputedPayloadHash}:${receipt.serverTimestamp}:${receipt.contributorId}:${receipt.scenarioVersion}`;
  const recomputedChainHash = sha256Hex(chainInput);

  const payloadMatches = recomputedPayloadHash === receipt.payloadSha256;
  const chainMatches = recomputedChainHash === receipt.chainSha256;

  return {
    verified: payloadMatches && chainMatches,
    recomputedPayloadHash,
    recomputedChainHash,
    payloadMatches,
    chainMatches,
    limitationsDisclosure:
      "Server-verified commitment: The UTC timestamp and initial SHA-256 hash commitment are generated by the FutureGraph server and protected by append-only Postgres triggers. While any subsequent payload tampering breaks the SHA-256 hash chain, independent external notarization (e.g., RFC 3161 transparency log anchoring) is planned for a future release.",
  };
}
